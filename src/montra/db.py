"""Postgres connection and schema."""

import psycopg
from psycopg.rows import dict_row

from montra.config import database_url

SCHEMA = """
-- The people who use the app. Every expense belongs to one of them.
CREATE TABLE IF NOT EXISTS users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      TEXT        UNIQUE,                   -- empty until sign-in exists
    name       TEXT        NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS expenses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users (id),  -- the owner
    spent_on     DATE        NOT NULL,
    amount_minor BIGINT      NOT NULL CHECK (amount_minor > 0),
    category     TEXT        NOT NULL,
    note         TEXT        NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_expenses_owner_date ON expenses (user_id, spent_on);

-- The login PIN, stored only as a salted hash (see auth.py).
CREATE TABLE IF NOT EXISTS auth (
    id   INTEGER PRIMARY KEY CHECK (id = 1),         -- only ever one row
    salt BYTEA   NOT NULL,
    hash BYTEA   NOT NULL,
    n    INTEGER NOT NULL,                           -- scrypt cost settings
    r    INTEGER NOT NULL,
    p    INTEGER NOT NULL
);

-- Wrong PIN tries, so the app can lock itself after too many (see auth.py).
CREATE TABLE IF NOT EXISTS login_attempts (
    id           INTEGER PRIMARY KEY CHECK (id = 1), -- only ever one row
    failed       INTEGER NOT NULL DEFAULT 0,         -- wrong tries in a row
    locked_until TIMESTAMPTZ                         -- or NULL
);
"""


def connect(url: str | None = None) -> psycopg.Connection:
    """Open a connection to the database.

    Each statement is saved straight away (autocommit). Code that must change
    several things together wraps them in `with conn.transaction():`.
    """
    return psycopg.connect(
        url or database_url(),
        autocommit=True,
        row_factory=dict_row,  # rows are read by column name: row["amount_minor"]
        prepare_threshold=None,  # needed when connecting through Neon's pooler
    )


def create_tables(conn: psycopg.Connection) -> None:
    """Create the tables if they do not exist yet. Safe to run more than once."""
    with conn.transaction():
        conn.execute(SCHEMA)
